#!/usr/bin/env python3
"""Build the multi-mode sources from the two single-mode projects.

    python3 tools/sync.py <path to BBQ-controller> <path to plant-controller2>

Each project's firmware is copied into its own folder (src/bbq, src/greenhouse) and wrapped in
a C++ namespace, so both can live in one firmware without name clashes. Only these changes are
made to the original code:

  * everything after the library #includes of the main .cpp is wrapped in `namespace <mode> {`
  * each mode gets its own EEPROM store (EEPROMClass with its own name), so BBQ and greenhouse
    settings are kept separately and survive switching modes
  * the web page is served from /<mode>/ in SPIFFS, shared files from /common/
  * the /mode routes (switch modes) are added to the web server, /info lists the modes

The web pages (data/) are copied too, with mode.js added for the mode switch.
Run it again after changing one of the original projects; never edit src/bbq or src/greenhouse
by hand.
"""

import pathlib
import re
import shutil
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent

MODES = [
    # (namespace, data dir, EEPROM store name, main .cpp file)
    ('bbq', 'bbq', 'eeprom_bbq', 'BBQ_pt100_ktype.cpp'),
    ('greenhouse', 'gh', 'eeprom_gh', 'BBQ_pt100_ktype.cpp'),
]

COMMON_DATA = ['ui.css', 'chart.js', 'alarm.mp3']

HEADER = '// GENERATED by tools/sync.py from {source} - do not edit, change the original project instead.\n'


def replace_once(text, old, new, where):
    if text.count(old) != 1:
        sys.exit(f'sync.py: expected exactly one "{old.strip()[:60]}" in {where}, found {text.count(old)}.'
                 ' The original code changed; update tools/sync.py.')
    return text.replace(old, new)


def split_prelude(lines):
    """Index of the first line that is real code (not a comment, blank line or # directive)."""
    in_block_comment = False
    for index, line in enumerate(lines):
        stripped = line.strip()
        if in_block_comment:
            if '*/' in stripped:
                in_block_comment = False
            continue
        if not stripped or stripped.startswith('//') or stripped.startswith('#'):
            continue
        if stripped.startswith('/*'):
            in_block_comment = '*/' not in stripped
            continue
        return index
    sys.exit('sync.py: no code found in main .cpp')


def wrap_main(text, namespace, store, source):
    lines = text.splitlines(keepends=True)
    start = split_prelude(lines)
    prelude = ''.join(lines[:start])
    body = ''.join(lines[start:])
    return (HEADER.format(source=source) + prelude
            + '#include "../common/mode.h"\n\n'
            + f'namespace {namespace} {{\n\n'
            + f'EEPROMClass EEPROM("{store}"); // this mode\'s own settings store, kept when switching modes\n\n'
            + body
            + f'\n}} // namespace {namespace}\n')


def patch_web_server(text, data_dir, source):
    text = replace_once(text, 'request->send(SPIFFS, "/index.html", "text/html");',
                        f'request->send(SPIFFS, "/{data_dir}/index.html", "text/html");', source)
    static = ('server.serveStatic("/", SPIFFS, "/");' if 'server.serveStatic("/", SPIFFS, "/");' in text
              else None)
    if static is None:
        sys.exit(f'sync.py: serveStatic not found in {source}')
    extra = f'server.serveStatic("/", SPIFFS, "/{data_dir}/");\n    server.serveStatic("/", SPIFFS, "/common/");\n    registerModeRoutes(server);'
    return replace_once(text, static, extra, source)


def patch_device_info(text, source):
    # the /info JSON ends with  + "}";  on its own line
    return replace_once(text, '              + "}";',
                        '              + ",\\"modes\\":" + modeListJson() + "}";', source)


def sync_mode(project, namespace, data_dir, store, main_cpp):
    src = project / 'src'
    out = ROOT / 'src' / namespace
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)

    for path in sorted(src.iterdir()):
        if path.suffix not in ('.h', '.cpp'):
            continue
        source = f'{project.name}/src/{path.name}'
        text = path.read_text()
        if path.name == main_cpp:
            text = wrap_main(text, namespace, store, source)
            (out / f'{namespace}.cpp').write_text(text)
            continue
        if path.name == 'websocketMessages.h':
            text = patch_web_server(text, data_dir, source)
        if path.name == 'deviceInfo.h':
            text = patch_device_info(text, source)
        (out / path.name).write_text(HEADER.format(source=source) + text)

    data_out = ROOT / 'data' / data_dir
    if data_out.exists():
        shutil.rmtree(data_out)
    data_out.mkdir(parents=True)
    for path in sorted((project / 'data').iterdir()):
        if path.name in COMMON_DATA or path.stat().st_size == 0:
            continue
        if path.name == 'index.html':
            html = replace_once(path.read_text(), '</body>', '<script src="mode.js" defer></script>\n</body>',
                                f'{project.name}/data/index.html')
            (data_out / path.name).write_text(html)
        else:
            shutil.copy(path, data_out / path.name)


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    bbq, greenhouse = (pathlib.Path(p).resolve() for p in sys.argv[1:])
    for project, (namespace, data_dir, store, main_cpp) in zip((bbq, greenhouse), MODES):
        sync_mode(project, namespace, data_dir, store, main_cpp)
    # shared web files: identical in both projects, served from /common/
    for name in COMMON_DATA:
        shutil.copy(bbq / 'data' / name, ROOT / 'data' / 'common' / name)
    print('synced', bbq, 'and', greenhouse)


if __name__ == '__main__':
    main()
